export async function issueContributionInvoice(input: IssueContributionInvoiceInput) {
  const db = getDb();
  const assessment = await db.registrationContributionAssessment.findFirst({
    where: {
      id: input.contributionAssessmentId,
      recordTier: "HOT",
      amReleasedAt: {
        not: null,
      },
    },
    select: {
      id: true,
      companyId: true,
      registrationApplicationId: true,
      recommendedAmount: true,
    },
  });

  if (!assessment) {
    throw new Error("A released contribution assessment was not found for invoice issuance.");
  }

  const issuer = await db.user.findUnique({
    where: {
      email: input.requesterEmail,
    },
    select: {
      id: true,
    },
  });

  if (!issuer) {
    throw new Error("Invoice issuer account was not found.");
  }

  return db.contributionInvoice.upsert({
    where: {
      contributionAssessmentId: assessment.id,
    },
    create: {
      companyId: assessment.companyId,
      registrationApplicationId: assessment.registrationApplicationId,
      contributionAssessmentId: assessment.id,
      issuedById: issuer.id,
      invoiceNumber: createInvoiceNumber(),
      amount: assessment.recommendedAmount,
    },
    update: {},
    select: {
      id: true,
    },
  });
}

export async function generateContributionInvoicePdf(
  input: GenerateContributionInvoicePdfInput,
) {
  if (!can(input.requesterRole, "company:read") && !can(input.requesterRole, "registry:review")) {
    throw new Error("You do not have permission to generate contribution invoices.");
  }

  const db = getDb();
  const invoice = await db.contributionInvoice.findFirst({
    where: {
      id: input.invoiceId,
      recordTier: "HOT",
      status: {
        in: ["ISSUED", "PAID"],
      },
    },
    select: {
      id: true,
      companyId: true,
      registrationApplicationId: true,
      invoiceNumber: true,
      amount: true,
      issuedAt: true,
      generatedDocumentId: true,
      company: {
        select: {
          organizationId: true,
          areaOfficeId: true,
          legalName: true,
          rcNumber: true,
          taxId: true,
          businessAddress: true,
        },
      },
    },
  });

  if (!invoice) {
    throw new Error("Contribution invoice was not found.");
  }

  const requester = await db.user.findUnique({
    where: {
      email: input.requesterEmail,
    },
    select: {
      id: true,
      memberships: {
        where: { isActive: true },
        select: {
          organizationId: true,
          areaOfficeId: true,
        },
      },
    },
  });

  if (!requester) {
    throw new Error("User account was not found.");
  }

  const hasAccess =
    isItfRole(input.requesterRole) ||
    requester.memberships.some(
      (membership) =>
        membership.organizationId === invoice.company.organizationId ||
        membership.areaOfficeId === invoice.company.areaOfficeId,
    );

  if (!hasAccess) {
    throw new Error("You do not have access to this contribution invoice.");
  }

  const buffer = await renderContributionInvoicePdf({
    invoiceNumber: invoice.invoiceNumber,
    issuedAt: invoice.issuedAt,
    companyName: invoice.company.legalName,
    rcNumber: invoice.company.rcNumber,
    taxId: invoice.company.taxId,
    businessAddress: invoice.company.businessAddress,
    amount: invoice.amount,
  });
  const fileName = sanitizeFileName(`${invoice.invoiceNumber}.pdf`);
  const stored = await uploadObject({
    buffer,
    companyId: invoice.companyId,
    extension: ".pdf",
    mimeType: "application/pdf",
    namespace: "contribution-invoices",
  });
  const generatedAt = new Date();

  return db.$transaction(async (tx) => {
    if (invoice.generatedDocumentId) {
      await tx.document.updateMany({
        where: {
          id: invoice.generatedDocumentId,
        },
        data: {
          isActive: false,
          revokedAt: generatedAt,
        },
      });
    }

    const document = await tx.document.create({
      data: {
        organizationId: invoice.company.organizationId,
        companyId: invoice.companyId,
        registrationApplicationId: invoice.registrationApplicationId,
        uploadedById: requester.id,
        kind: "CONTRIBUTION_INVOICE",
        fileName,
        storageProvider: stored.storageProvider,
        scanStatus: stored.scanStatus,
        scannedAt: stored.scannedAt,
        scanReason: stored.scanReason,
        bucket: stored.bucket,
        objectKey: stored.objectKey,
        url: stored.url,
        etag: stored.etag,
        versionId: stored.versionId,
        checksum: stored.checksum,
        mimeType: stored.mimeType,
        fileSize: stored.fileSize,
        access: "PRIVATE",
        classification: "OFFICIAL",
      },
      select: {
        id: true,
      },
    });

    return tx.contributionInvoice.update({
      where: {
        id: invoice.id,
      },
      data: {
        generatedDocumentId: document.id,
        generatedAt,
      },
      select: {
        id: true,
        generatedDocumentId: true,
        generatedAt: true,
      },
    });
  });
}

export async function issueAndGenerateContributionInvoice(input: IssueContributionInvoiceInput) {
  const invoice = await issueContributionInvoice(input);
  return generateContributionInvoicePdf({
    invoiceId: invoice.id,
    requesterEmail: input.requesterEmail,
    requesterRole: input.requesterRole,
  });
}

export async function downloadContributionInvoice(input: DownloadContributionInvoiceInput) {
  if (!can(input.requesterRole, "company:read")) {
    throw new Error("You do not have permission to read contribution invoices.");
  }

  const db = getDb();
  const invoice = await db.contributionInvoice.findFirst({
    where: {
      id: input.invoiceId,
      companyId: input.companyId,
      recordTier: "HOT",
      generatedDocumentId: {
        not: null,
      },
    },
    select: {
      generatedDocumentId: true,
    },
  });

  if (!invoice?.generatedDocumentId) {
    return null;
  }

  const document = await db.document.findFirst({
    where: {
      id: invoice.generatedDocumentId,
      companyId: input.companyId,
      kind: "CONTRIBUTION_INVOICE",
      isActive: true,
      recordTier: "HOT",
      revokedAt: null,
    },
    select: {
      organizationId: true,
      fileName: true,
      storageProvider: true,
      bucket: true,
      objectKey: true,
      mimeType: true,
      fileSize: true,
      access: true,
    },
  });

  if (!document) {
    return null;
  }

  if (document.access !== "PRIVATE") {
    throw new Error("Unsupported contribution invoice access policy.");
  }

  const requester = await db.user.findUnique({
    where: {
      email: input.requesterEmail,
    },
    select: {
      memberships: {
        where: { isActive: true },
        select: {
          organizationId: true,
        },
      },
    },
  });

  if (!requester) {
    throw new Error("User account was not found.");
  }

  const hasAccess =
    isItfRole(input.requesterRole) ||
    requester.memberships.some(
      (membership) => membership.organizationId === document.organizationId,
    );

  if (!hasAccess) {
    throw new Error("You do not have access to this contribution invoice.");
  }

  const downloaded = await downloadObject({
    storageProvider: document.storageProvider,
    bucket: document.bucket,
    objectKey: document.objectKey,
  });

  return {
    buffer: downloaded.buffer,
    fileName: document.fileName,
    fileSize: downloaded.fileSize,
    mimeType: document.mimeType,
  };
}
