import { randomUUID } from "node:crypto";

import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

import { getDb } from "@/lib/db";
import { appName } from "@/lib/domain";
import { can, isItfRole, type Role } from "@/lib/rbac";
import { downloadObject, uploadObject } from "@/lib/storage";
import { sanitizeFileName } from "@/lib/storage/security";

type InvoiceRequester = {
  requesterEmail: string;
  requesterRole: Role;
};

export type IssueContributionInvoiceInput = InvoiceRequester & {
  contributionAssessmentId: string;
};

export type GenerateContributionInvoicePdfInput = InvoiceRequester & {
  invoiceId: string;
};

export type DownloadContributionInvoiceInput = InvoiceRequester & {
  companyId: string;
  invoiceId: string;
};

function createInvoiceNumber() {
  return `ITF-INV-${new Date().getFullYear()}-${randomUUID().slice(0, 8).toUpperCase()}`;
}

function formatMoney(value: { toString(): string }) {
  return `NGN ${Number(value.toString()).toLocaleString("en-NG", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
}

function formatDate(value: Date) {
  return new Intl.DateTimeFormat("en-NG", { dateStyle: "long" }).format(value);
}

